// {{tokenName}} 樣板變數代入——PDF（contractPdfShared 消費端）與前端 ContractTermsSections 共用同一套規則。
function fillTemplate(text, vars) {
  return String(text || '').replace(/\{\{(\w+)\}\}/g, (_, k) => (vars && vars[k] != null ? vars[k] : `{{${k}}}`));
}

